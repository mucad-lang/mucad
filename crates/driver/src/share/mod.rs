//! Links to share µcad code in the web viewer, which contain the code.
//!
//! The code is lexed into [symbols](SharedSymbol), which are serialized behind an
//! [`ArtifactHeader`] of the kind [`ArtifactKind::Tokens`]: the number of symbols in Elias gamma
//! code, followed by each symbol as 2 bits for its category and its Huffman code:
//!
//! - `00` whitespace: a space, a new line or an empty line, the code is formatted when it is
//!   decoded,
//! - `01` a structural token, e.g. `fn` or `(`,
//! - `10` an identifier: a code of the built-in dictionary, or the escape code followed by the
//!   index of an identifier of the code, e.g. a new identifier, which is spelled once,
//! - `11` a fragment of source code, e.g. `10mm` or a comment: its length in Elias gamma code
//!   and its characters.
//!
//! The tables are generated by `cargo xtask share-tables` from µcad files.

