/// The web viewer, which shows the code of a link in its fragment.
///
/// The fragment is not sent to the server, so the web viewer can be a static page, and the code
/// is not logged by the server.
pub const PLAY_URL: &str = "https://play.mucad.org/#";

/// The maximum size of the code in a link, in bytes of its UTF-8 encoding.
pub const MAX_CODE_BYTES: usize = 2048;

/// The maximum size of serialized code, see [`serialize`].
///
/// A byte of code has at most 7 bytes: a character, which is not in the table, has about
/// 40 bits.
const MAX_SERIALIZED_BYTES: usize = ArtifactHeader::SIZE + 7 * MAX_CODE_BYTES;

/// The number of bits of the code point of a character, which is not in the table.
const CODE_POINT_BITS: u8 = 21;

/// The bits of the categories of symbols.
const WHITESPACE: u32 = 0b00;
const STRUCTURAL: u32 = 0b01;
const IDENTIFIER: u32 = 0b10;
const FRAGMENT: u32 = 0b11;

/// An error of sharing code.
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum ShareError {
    /// The code is too long for a link.
    #[error("the code has {0} bytes, a link can contain at most {MAX_CODE_BYTES} bytes")]
    TooLong(usize),
    /// The tokens of the code cannot be serialized, so they are lexed again.
    #[error("the code cannot be shared, its tokens change when they are written again")]
    Unsupported,
    /// The link contains no valid base64.
    #[error("the link contains no valid code: {0}")]
    InvalidBase64(String),
    /// The link contains no valid serialized code.
    #[error("the link contains no valid code: {0}")]
    InvalidData(String),
}

/// A symbol of shared code.
#[derive(Debug, Clone, PartialEq)]
pub enum SharedSymbol {
    /// Whitespace: `" "`, `"\n"` or an empty line `"\n\n"`.
    Whitespace(&'static str),
    /// A token with a fixed text, e.g. `fn`.
    Structural {
        /// The kind of the token, e.g. `Keyword(Fn)`.
        kind: String,
        /// The text of the token, e.g. `fn`.
        text: &'static str,
    },
    /// An identifier, e.g. `width`.
    Identifier(String),
    /// Source code of other tokens, e.g. `10mm`, a comment or a string.
    Fragment(String),
}

/// The tokens with a fixed text, except keywords, with their texts.
const FIXED_TOKENS: &[(Token<'static>, &str)] = &[
    (Token::LiteralBool(true), "true"),
    (Token::LiteralBool(false), "false"),
    (Token::SigilQuote, "\""),
    (Token::SigilColon, ":"),
    (Token::SigilSemiColon, ";"),
    (Token::SigilDoubleColon, "::"),
    (Token::SigilOpenBracket, "("),
    (Token::SigilCloseBracket, ")"),
    (Token::SigilOpenSquareBracket, "["),
    (Token::SigilCloseSquareBracket, "]"),
    (Token::SigilOpenCurlyBracket, "{"),
    (Token::SigilCloseCurlyBracket, "}"),
    (Token::SigilHash, "#"),
    (Token::SigilDot, "."),
    (Token::SigilComma, ","),
    (Token::SigilDoubleDot, ".."),
    (Token::SigilAt, "@"),
    (Token::SigilSingleArrow, "->"),
    (Token::OperatorAdd, "+"),
    (Token::OperatorSubtract, "-"),
    (Token::OperatorMultiply, "*"),
    (Token::OperatorDivide, "/"),
    (Token::OperatorUnion, "|"),
    (Token::OperatorIntersect, "&"),
    (Token::OperatorPowerXor, "^"),
    (Token::OperatorGreaterThan, ">"),
    (Token::OperatorLessThan, "<"),
    (Token::OperatorGreaterEqual, ">="),
    (Token::OperatorLessEqual, "<="),
    (Token::OperatorNear, "~"),
    (Token::OperatorEqual, "=="),
    (Token::OperatorNotEqual, "!="),
    (Token::OperatorAnd, "and"),
    (Token::OperatorOr, "or"),
    (Token::OperatorXor, "xor"),
    (Token::OperatorNot, "!"),
    (Token::OperatorAssignment, "="),
];

/// The kinds and texts of all structural tokens, e.g. `Keyword(Fn)` and `fn`.
pub fn structural_tokens() -> impl Iterator<Item = (String, &'static str)> {
    let keywords = Keyword::all().map(Token::Keyword);
    let fixed = FIXED_TOKENS.iter().map(|(token, _)| token.clone());
    keywords.chain(fixed).map(|token| {
        let text = fixed_text(&token).expect("A structural token");
        (token_kind(&token), text)
    })
}

/// The kind of a token, the name of its variant, with the keyword or boolean,
/// e.g. `Identifier`, `Keyword(Fn)` or `LiteralBool(true)`.
fn token_kind(token: &Token) -> String {
    let name = format!("{token:?}");
    match token {
        Token::Keyword(_) | Token::LiteralBool(_) => name,
        _ => match name.split_once('(') {
            Some((variant, _)) => variant.to_string(),
            None => name,
        },
    }
}

/// The text of a structural token, e.g. `fn`.
fn fixed_text(token: &Token) -> Option<&'static str> {
    match token {
        Token::Keyword(keyword) => Some(keyword.as_str()),
        token => FIXED_TOKENS
            .iter()
            .find(|(fixed, _)| fixed == token)
            .map(|(_, text)| *text),
    }
}

/// The structural token of a kind with a text, see [`structural_tokens`].
fn structural_token(kind: &str, text: &str) -> Option<Token<'static>> {
    match kind.starts_with("Keyword(") {
        true => text.parse().ok().map(Token::Keyword),
        false => FIXED_TOKENS
            .iter()
            .find(|(token, _)| token_kind(token) == kind)
            .map(|(token, _)| token.clone()),
    }
}

/// The lexer options for sharing code: whitespace of formatted code and optionally without
/// comments.
fn lex_options(strip: bool) -> LexOptions {
    LexOptions {
        strip_comments: strip,
        normalize_whitespace: true,
    }
}

/// The text of a token in the source code, `None` for a lexer error.
///
/// The format of a format string starts with `:`, which is no token, so the first format
/// token after the `previous` token contains it.
fn source_text<'a>(token: &'a Token, previous: Option<&Token>) -> Option<Cow<'a, str>> {
    let is_format = |token: &Token| {
        matches!(
            token,
            Token::StringFormatPrecision(_) | Token::StringFormatWidth(_)
        )
    };
    Some(match token {
        Token::Whitespace(text)
        | Token::SingleLineComment(text)
        | Token::DocComment(text)
        | Token::InnerDocComment(text)
        | Token::Identifier(text)
        | Token::Unit(text)
        | Token::LiteralInt(text)
        | Token::LiteralFloat(text)
        | Token::StringContent(text) => Cow::Borrowed(text),
        Token::StringFormatPrecision(text) | Token::StringFormatWidth(text) => {
            match previous.is_some_and(is_format) {
                true => Cow::Borrowed(text),
                false => format!(":{text}").into(),
            }
        }
        // The comment is lexed without `/*`, `*/` and whitespace.
        Token::MultiLineComment(text) => format!("/* {text} */").into(),
        Token::LiteralString(text) => {
            let mut literal = String::from('"');
            for c in text.chars() {
                match escape_char(c) {
                    Some(escaped) => literal.push_str(escaped),
                    None => literal.push(c),
                }
            }
            literal.push('"');
            literal.into()
        }
        // An escaped character, e.g. `\/`, which is no escape sequence by `escape_char`.
        Token::Character(c) => match escape_char(*c) {
            Some(escaped) => escaped.into(),
            None => format!("\\{c}").into(),
        },
        Token::FormatStringStart | Token::FormatStringEnd => "\"".into(),
        Token::StringFormatOpen => "{".into(),
        Token::StringFormatClose => "}".into(),
        Token::Error(_) => return None,
        token => fixed_text(token)?.into(),
    })
}

/// The symbols of the µcad `code` for sharing, with `strip` without comments and whitespace
/// at the start.
///
/// Format strings are fragments, consecutive tokens of other kinds are one fragment, e.g.
/// `10.5`.
pub fn shared_symbols(code: &str, strip: bool) -> Vec<SharedSymbol> {
    let mut symbols = Vec::new();
    let mut fragment = String::new();
    // The depth of nested format strings.
    let mut depth = 0usize;
    let mut previous: Option<Token> = None;
    for token in mu::parse::lex_with(code, lex_options(strip)) {
        let in_string = depth > 0 || token.value == Token::FormatStringStart;
        match token.value {
            Token::FormatStringStart => depth += 1,
            Token::FormatStringEnd => depth = depth.saturating_sub(1),
            _ => (),
        }
        let symbol = match &token.value {
            _ if in_string => None,
            Token::Whitespace(text) => Some(SharedSymbol::Whitespace(normalized_whitespace(text))),
            Token::Identifier(name) => Some(SharedSymbol::Identifier(name.to_string())),
            token => fixed_text(token).map(|text| SharedSymbol::Structural {
                kind: token_kind(token),
                text,
            }),
        };
        match symbol {
            Some(symbol) => {
                if !fragment.is_empty() {
                    symbols.push(SharedSymbol::Fragment(std::mem::take(&mut fragment)));
                }
                symbols.push(symbol);
            }
            None => match source_text(&token.value, previous.as_ref()) {
                Some(text) => fragment.push_str(&text),
                // The text of a lexer error is the erroneous code.
                None => fragment.push_str(code.get(token.span.clone()).unwrap_or_default()),
            },
        }
        previous = Some(token.value);
    }
    if !fragment.is_empty() {
        symbols.push(SharedSymbol::Fragment(fragment));
    }
    // Comments at the start leave whitespace.
    if strip {
        let start = symbols
            .iter()
            .take_while(|symbol| matches!(symbol, SharedSymbol::Whitespace(_)))
            .count();
        symbols.drain(..start);
    }
    symbols
}

/// Deserialized code: its tokens and their source code.
#[derive(Debug)]
pub struct SharedCode {
    /// The source code of the tokens.
    pub code: String,
    /// The tokens with their spans in the source code.
    pub tokens: Vec<Spanned<Token<'static>>>,
}

impl SharedCode {
    /// The code and the tokens of `symbols`, fragments are lexed.
    fn new(symbols: &[SharedSymbol]) -> Result<Self, ShareError> {
        let mut code = String::new();
        let mut tokens = Vec::new();
        for symbol in symbols {
            let start = code.len();
            let token = match symbol {
                SharedSymbol::Whitespace(text) => Token::Whitespace(Cow::Borrowed(*text)),
                SharedSymbol::Structural { kind, text } => structural_token(kind, text)
                    .ok_or_else(|| ShareError::InvalidData(format!("unknown token {kind}")))?,
                SharedSymbol::Identifier(name) => Token::Identifier(name.clone().into()),
                SharedSymbol::Fragment(text) => {
                    code.push_str(text);
                    tokens.extend(mu::parse::lex(text).map(|token| {
                        let span = token.span.start + start..token.span.end + start;
                        Spanned::new(span, token.value.into_owned())
                    }));
                    continue;
                }
            };
            code.push_str(match symbol {
                SharedSymbol::Whitespace(text) => text,
                SharedSymbol::Structural { text, .. } => text,
                SharedSymbol::Identifier(name) => name,
                SharedSymbol::Fragment(_) => unreachable!("A fragment is lexed"),
            });
            tokens.push(Spanned::new(start..code.len(), token));
        }
        Ok(Self { code, tokens })
    }
}

/// The tokens with whitespace of formatted code and without the details of lexer errors,
/// which do not change the formatted code.
fn normalized<'a>(tokens: impl Iterator<Item = Token<'a>>) -> Vec<Token<'a>> {
    tokens
        .map(|token| match token {
            Token::Whitespace(text) => {
                Token::Whitespace(Cow::Borrowed(normalized_whitespace(&text)))
            }
            Token::Error(_) => Token::Error(LexerError::NoValidToken),
            token => token,
        })
        .collect()
}

/// A Huffman table: the codes by the symbols and the symbols by the codes.
struct Table<T> {
    codes: HashMap<T, (u32, u8)>,
    symbols: HashMap<(u32, u8), T>,
}

impl<T: Copy + Eq + Hash> Table<T> {
    fn new(rows: impl IntoIterator<Item = (T, u32, u8)>) -> Self {
        let rows: Vec<_> = rows.into_iter().collect();
        Self {
            codes: rows
                .iter()
                .map(|(symbol, code, bits)| (*symbol, (*code, *bits)))
                .collect(),
            symbols: rows
                .iter()
                .map(|(symbol, code, bits)| ((*code, *bits), *symbol))
                .collect(),
        }
    }

    /// Write the code of `symbol`, fails if it is not in the table.
    fn write(&self, writer: &mut BitWriter, symbol: &T) -> Result<(), ShareError> {
        let (code, bits) = self.codes.get(symbol).ok_or(ShareError::Unsupported)?;
        writer.write(*code, *bits);
        Ok(())
    }

    /// Read the next symbol.
    fn read(&self, reader: &mut BitReader) -> Result<T, ShareError> {
        let mut code = 0;
        for bits in 1..=32 {
            let bit = reader.read().ok_or_else(too_short)?;
            code = code << 1 | bit as u32;
            if let Some(symbol) = self.symbols.get(&(code, bits)) {
                return Ok(*symbol);
            }
        }
        Err(ShareError::InvalidData("unknown code".into()))
    }
}

/// The error of data, which ends too early.
fn too_short() -> ShareError {
    ShareError::InvalidData("the code ends too early".into())
}

/// The table of whitespace.
static WHITESPACES: LazyLock<Table<&str>> =
    LazyLock::new(|| Table::new(tables::WHITESPACES.iter().copied()));

/// The table of structural tokens by their kinds.
static STRUCTURALS: LazyLock<Table<&str>> = LazyLock::new(|| {
    Table::new(
        tables::STRUCTURALS
            .iter()
            .map(|(kind, _, code, bits)| (*kind, *code, *bits)),
    )
});

/// The texts of the structural tokens by their kinds.
static STRUCTURAL_TEXTS: LazyLock<HashMap<&str, &str>> = LazyLock::new(|| {
    tables::STRUCTURALS
        .iter()
        .map(|(kind, text, _, _)| (*kind, *text))
        .collect()
});

/// The table of identifiers, `None` is an identifier of the code.
static IDENTIFIERS: LazyLock<Table<Option<&str>>> = LazyLock::new(|| {
    Table::new(
        (tables::IDENTIFIERS.iter())
            .map(|(name, code, bits)| (Some(*name), *code, *bits))
            .chain([(None, tables::IDENTIFIER_LOCAL.0, tables::IDENTIFIER_LOCAL.1)]),
    )
});

/// The tables of characters of identifiers and fragments, `None` is another character.
static IDENTIFIER_CHARS: LazyLock<Table<Option<char>>> =
    LazyLock::new(|| char_table(tables::IDENTIFIER_CHARS, tables::IDENTIFIER_CHAR_OTHER));
static FRAGMENT_CHARS: LazyLock<Table<Option<char>>> =
    LazyLock::new(|| char_table(tables::FRAGMENT_CHARS, tables::FRAGMENT_CHAR_OTHER));

fn char_table(chars: &[(char, u32, u8)], other: (u32, u8)) -> Table<Option<char>> {
    Table::new(
        (chars.iter())
            .map(|(c, code, bits)| (Some(*c), *code, *bits))
            .chain([(None, other.0, other.1)]),
    )
}

/// Write the length of `text` and its characters.
fn write_text(
    writer: &mut BitWriter,
    table: &Table<Option<char>>,
    text: &str,
) -> Result<(), ShareError> {
    writer.write_gamma(text.chars().count() as u32);
    for c in text.chars() {
        match table.codes.contains_key(&Some(c)) {
            true => table.write(writer, &Some(c))?,
            false => {
                table.write(writer, &None)?;
                writer.write(c as u32, CODE_POINT_BITS);
            }
        }
    }
    Ok(())
}

/// Read a text, see [`write_text`].
fn read_text(reader: &mut BitReader, table: &Table<Option<char>>) -> Result<String, ShareError> {
    let length = reader.read_gamma().ok_or_else(too_short)?;
    if length as usize > MAX_CODE_BYTES {
        return Err(ShareError::TooLong(length as usize));
    }
    (0..length)
        .map(|_| match table.read(reader)? {
            Some(c) => Ok(c),
            None => reader
                .read_bits(CODE_POINT_BITS)
                .and_then(char::from_u32)
                .ok_or_else(|| ShareError::InvalidData("invalid character".into())),
        })
        .collect()
}

/// The number of bits of an index of `count` values.
fn index_bits(count: usize) -> u8 {
    (usize::BITS - (count.max(1) - 1).leading_zeros()) as u8
}

/// Serialize the symbols of the µcad `code` behind an artifact header, see the
/// [module](self), with `strip` without comments.
///
/// Fails, if the code has more than [`MAX_CODE_BYTES`] bytes, without comments with `strip`,
/// or if its tokens cannot be serialized.
pub fn serialize(code: &str, strip: bool) -> Result<Vec<u8>, ShareError> {
    let symbols = shared_symbols(code, strip);
    let shared = SharedCode::new(&symbols)?;
    let length = match strip {
        true => shared.code.len(),
        false => code.len(),
    };
    if length > MAX_CODE_BYTES {
        return Err(ShareError::TooLong(length));
    }

    // The deserialized code must have the same tokens.
    let lexed = mu::parse::lex_with(code, lex_options(strip))
        .map(|token| token.value)
        .skip_while(|token| strip && matches!(token, Token::Whitespace(_)));
    let lexed = normalized(lexed);
    if normalized(shared.tokens.into_iter().map(|token| token.value)) != lexed {
        return Err(ShareError::Unsupported);
    }

    let mut writer = BitWriter::default();
    writer.write_gamma(symbols.len() as u32 + 1);
    // The identifiers of the code, which are not in the dictionary.
    let mut locals: Vec<&str> = Vec::new();
    for symbol in &symbols {
        match symbol {
            SharedSymbol::Whitespace(text) => {
                writer.write(WHITESPACE, 2);
                WHITESPACES.write(&mut writer, text)?;
            }
            SharedSymbol::Structural { kind, .. } => {
                writer.write(STRUCTURAL, 2);
                STRUCTURALS.write(&mut writer, &kind.as_str())?;
            }
            SharedSymbol::Identifier(name) => {
                writer.write(IDENTIFIER, 2);
                if IDENTIFIERS.codes.contains_key(&Some(name.as_str())) {
                    IDENTIFIERS.write(&mut writer, &Some(name.as_str()))?;
                    continue;
                }
                IDENTIFIERS.write(&mut writer, &None)?;
                // The index after the identifiers of the code is a new identifier.
                let bits = index_bits(locals.len() + 1);
                match locals.iter().position(|local| local == name) {
                    Some(index) => writer.write(index as u32, bits),
                    None => {
                        writer.write(locals.len() as u32, bits);
                        write_text(&mut writer, &IDENTIFIER_CHARS, name)?;
                        locals.push(name);
                    }
                }
            }
            SharedSymbol::Fragment(text) => {
                writer.write(FRAGMENT, 2);
                write_text(&mut writer, &FRAGMENT_CHARS, text)?;
            }
        }
    }

    let header = ArtifactHeader::from(ArtifactKind::Tokens);
    let mut bytes = postcard::to_allocvec(&header).map_err(|_| ShareError::Unsupported)?;
    bytes.extend(writer.finish());
    Ok(bytes)
}

/// The symbols of serialized code.
fn read_symbols(reader: &mut BitReader) -> Result<Vec<SharedSymbol>, ShareError> {
    let count = reader.read_gamma().ok_or_else(too_short)? as usize - 1;
    if count > MAX_CODE_BYTES {
        return Err(ShareError::TooLong(count));
    }
    let mut symbols = Vec::with_capacity(count);
    let mut locals: Vec<String> = Vec::new();
    for _ in 0..count {
        let category = reader.read_bits(2).ok_or_else(too_short)?;
        symbols.push(match category {
            WHITESPACE => SharedSymbol::Whitespace(WHITESPACES.read(reader)?),
            STRUCTURAL => {
                let kind = STRUCTURALS.read(reader)?;
                SharedSymbol::Structural {
                    kind: kind.to_string(),
                    text: STRUCTURAL_TEXTS[kind],
                }
            }
            IDENTIFIER => match IDENTIFIERS.read(reader)? {
                Some(name) => SharedSymbol::Identifier(name.to_string()),
                None => {
                    let index = reader
                        .read_bits(index_bits(locals.len() + 1))
                        .ok_or_else(too_short)? as usize;
                    if index == locals.len() {
                        locals.push(read_text(reader, &IDENTIFIER_CHARS)?);
                    }
                    let name = locals.get(index).ok_or_else(|| {
                        ShareError::InvalidData(format!("unknown identifier {index}"))
                    })?;
                    SharedSymbol::Identifier(name.clone())
                }
            },
            _ => SharedSymbol::Fragment(read_text(reader, &FRAGMENT_CHARS)?),
        });
    }
    Ok(symbols)
}

/// The tokens of serialized code and their source code, see [`serialize`].
///
/// Fails, if the bytes are no tokens of a compatible version.
pub fn deserialize(bytes: &[u8]) -> Result<SharedCode, ShareError> {
    if bytes.len() > MAX_SERIALIZED_BYTES {
        return Err(ShareError::TooLong(bytes.len()));
    }
    let (header, data): (ArtifactHeader, _) = postcard::take_from_bytes(bytes)
        .map_err(|err| ShareError::InvalidData(format!("no shared code: {err}")))?;
    if header.kind != ArtifactKind::Tokens {
        return Err(ShareError::InvalidData(format!(
            "an artifact of kind {} instead of tokens",
            header.kind
        )));
    }
    if !header.version.is_compatible() {
        return Err(ShareError::InvalidData(format!(
            "the code is shared by the incompatible version {}",
            header.version
        )));
    }
    SharedCode::new(&read_symbols(&mut BitReader::new(data))?)
}

/// The link to the web viewer with `code`, whose [serialized](serialize) tokens are embedded
/// as URL-safe base64, e.g. `https://play.mucad.org/#tUAGABdAmvhY-mNSPw` for
/// `Circle(r = 1mm);`.
///
/// With `strip`, the link contains the code without comments. Fails, if the code cannot be
/// serialized.
pub fn link(code: &str, strip: bool) -> Result<String, ShareError> {
    Ok(format!(
        "{PLAY_URL}{}",
        URL_SAFE_NO_PAD.encode(serialize(code, strip)?)
    ))
}

/// The link data of a link: after `#`, as `?code=`, in the path or the link is the data.
fn link_data(link: &str) -> &str {
    let link = link.trim();
    if let Some((_, data)) = link.split_once('#') {
        data
    } else if let Some((_, query)) = link.split_once('?') {
        query
            .split('&')
            .find_map(|parameter| parameter.strip_prefix("code="))
            .unwrap_or(query)
    } else {
        // Former links have the code in their path.
        link.strip_prefix(PLAY_URL.trim_end_matches('#'))
            .unwrap_or(link)
    }
}

/// The formatted code of a link, see [`link`].
///
/// The link is a complete link with the code after `#`, as `?code=` or in its path, or only
/// the link data, e.g. `tUAGABdAmvhY-mNSPw`. Padding with `=` is optional.
///
/// The tokens are parsed and the code is formatted, code with errors is returned unformatted.
pub fn decode(link: &str) -> Result<String, ShareError> {
    let data = link_data(link);
    // A longer link contains more code than allowed, which is not decoded.
    if data.len() > MAX_SERIALIZED_BYTES.div_ceil(3) * 4 {
        return Err(ShareError::TooLong(data.len() / 4 * 3));
    }
    let engine = GeneralPurpose::new(
        &URL_SAFE,
        GeneralPurposeConfig::new().with_decode_padding_mode(DecodePaddingMode::Indifferent),
    );
    let bytes = engine
        .decode(data)
        .map_err(|err| ShareError::InvalidBase64(err.to_string()))?;
    let shared = deserialize(&bytes)?;
    let source = mu::Source::from(shared.code.as_str());
    Ok(
        match mu::parse::Ast::from_tokens(&shared.tokens, &(&source).into()) {
            Ok(ast) => mu::format::format_ast(&ast, &mu::FormatConfig::default()),
            Err(_) => shared.code,
        },
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Serialize and deserialize `code`: the tokens and the tokens of the source code are the
    /// tokens of the code with the whitespace of formatted code.
    fn assert_shared(code: &str) {
        let lexed = || {
            let tokens = mu::parse::lex_with(code, lex_options(false));
            normalized(tokens.map(|token| token.value.into_owned()))
        };
        let bytes = serialize(code, false).expect(code);
        let shared = deserialize(&bytes).expect(code);
        let tokens = shared.tokens.iter().map(|token| token.value.clone());
        assert_eq!(normalized(tokens), lexed(), "{code}");
        let source_tokens = mu::parse::lex(&shared.code).map(|token| token.value.into_owned());
        assert_eq!(normalized(source_tokens), lexed(), "{code}");
        // The spans are in the source code.
        for token in &shared.tokens {
            assert!(shared.code.get(token.span.clone()).is_some(), "{code}");
        }
    }

    /// The codes are complete prefix codes: no code is the start of another one.
    #[test]
    fn complete_tables() {
        fn kraft(bits: impl Iterator<Item = u8>) -> f64 {
            bits.map(|bits| 0.5f64.powi(bits as i32)).sum()
        }
        assert_eq!(kraft(tables::WHITESPACES.iter().map(|row| row.2)), 1.0);
        assert_eq!(kraft(tables::STRUCTURALS.iter().map(|row| row.3)), 1.0);
        let identifiers = tables::IDENTIFIERS.iter().map(|row| row.2);
        assert_eq!(kraft(identifiers.chain([tables::IDENTIFIER_LOCAL.1])), 1.0);
        let chars = tables::IDENTIFIER_CHARS.iter().map(|row| row.2);
        assert_eq!(kraft(chars.chain([tables::IDENTIFIER_CHAR_OTHER.1])), 1.0);
        let chars = tables::FRAGMENT_CHARS.iter().map(|row| row.2);
        assert_eq!(kraft(chars.chain([tables::FRAGMENT_CHAR_OTHER.1])), 1.0);

        // Every structural token is in the table.
        for (kind, text) in structural_tokens() {
            assert_eq!(STRUCTURAL_TEXTS.get(kind.as_str()), Some(&text), "{kind}");
        }
    }

    /// Code is split into whitespace, structural tokens, identifiers and fragments, e.g. a
    /// unit is an identifier.
    #[test]
    fn symbols() {
        use SharedSymbol::*;
        assert_eq!(
            shared_symbols("x = 10mm;\n    s = \"a {x} b\"; // c\n\n\n", false),
            [
                Identifier("x".into()),
                Whitespace(" "),
                Structural {
                    kind: "OperatorAssignment".into(),
                    text: "="
                },
                Whitespace(" "),
                Fragment("10".into()),
                Identifier("mm".into()),
                Structural {
                    kind: "SigilSemiColon".into(),
                    text: ";"
                },
                Whitespace("\n"),
                Identifier("s".into()),
                Whitespace(" "),
                Structural {
                    kind: "OperatorAssignment".into(),
                    text: "="
                },
                Whitespace(" "),
                Fragment("\"a {x} b\"".into()),
                Structural {
                    kind: "SigilSemiColon".into(),
                    text: ";"
                },
                Whitespace(" "),
                Fragment("// c".into()),
                Whitespace("\n\n"),
            ]
        );
    }

    /// With `strip`, comments are removed, also before the length of the code is checked.
    #[test]
    fn strip_comments() {
        use SharedSymbol::*;
        let code = "// c\nx = 1/* y */;\n";
        assert_eq!(
            shared_symbols(code, true),
            [
                Identifier("x".into()),
                Whitespace(" "),
                Structural {
                    kind: "OperatorAssignment".into(),
                    text: "="
                },
                Whitespace(" "),
                Fragment("1".into()),
                Whitespace(" "),
                Structural {
                    kind: "SigilSemiColon".into(),
                    text: ";"
                },
                Whitespace("\n"),
            ]
        );
        let stripped = link(code, true).expect("A link");
        assert!(stripped.len() < link(code, false).expect("A link").len());
        assert_eq!(decode(&stripped).as_deref(), Ok("x = 1;\n"));

        let long = format!("// {}\nCircle(r = 10mm);\n", "x".repeat(MAX_CODE_BYTES));
        assert!(matches!(link(&long, false), Err(ShareError::TooLong(2070))));
        assert!(link(&long, true).is_ok());
    }

    /// The serialized code starts with the header of tokens, followed by about half the bytes
    /// of the code.
    #[test]
    fn serialize_code() {
        let code = "Circle(r = 1mm);";
        let bytes = serialize(code, false).expect("Serialized code");
        assert_eq!(bytes[..2], [0xb5, (ArtifactKind::Tokens as u8) << 4]);
        assert!(bytes.len() - ArtifactHeader::SIZE < code.len() * 2 / 3);
        let shared = deserialize(&bytes).expect("Deserialized code");
        assert_eq!(shared.code, code);
        assert_eq!(shared.tokens[0].value, Token::Identifier("Circle".into()));
        assert_eq!(shared.tokens[0].span, 0..6);
    }

    /// The tokens of code are deserialized into the code again, also identifiers, which are
    /// not in the dictionary, unknown characters and lexer errors.
    #[test]
    fn serialize_tokens() {
        for code in [
            "",
            "// µcad\nsketch S(r: Length) {\n    Circle(r);\n}\n",
            "x = false; enum xyz_abc = xyz_abc + xyz_abc + other;",
            "s = \"a {x:05.2} b {{ }} \\n\";",
            "t = \"a\\\"{{}} \\n\\t\\r\\b\\f\\\\\\/\";",
            "/*  comment */ x = 1;",
            "x = 1 ~ 2 $ ☃;",
            "a = \"unclosed",
        ] {
            assert_shared(code);
        }
    }

    /// The code of every µcad file of the examples and the standard library can be shared.
    #[test]
    fn serialize_files() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        for dir in ["examples", "crates/std/lib/std"] {
            for entry in std::fs::read_dir(root.join(dir)).expect("A directory") {
                let path = entry.expect("An entry").path();
                if path.extension().is_some_and(|ext| ext == "mu") {
                    let code = std::fs::read_to_string(&path).expect("A file");
                    if code.len() <= MAX_CODE_BYTES {
                        assert_shared(&code);
                    }
                }
            }
        }
    }

    /// Code with more than 2048 bytes is too long for a link.
    #[test]
    fn link_too_long() {
        assert!(link(&"a".repeat(MAX_CODE_BYTES), false).is_ok());
        // `µ` has two bytes.
        assert_eq!(
            link(&"µ".repeat(MAX_CODE_BYTES / 2 + 1), false),
            Err(ShareError::TooLong(2050))
        );
    }

    /// The code of a link is decoded formatted, also from the fragment or query of a link.
    #[test]
    fn decode_link() {
        assert_eq!(
            link("Circle(r = 1mm);", false),
            Ok("https://play.mucad.org/#tUAGABdAmvhY-mNSPw".to_string())
        );
        let link = link("// µcad?>>\nCircle( r=1mm );\n", false).expect("A link");
        let data = link.strip_prefix(PLAY_URL).expect("The web viewer");
        assert!(
            data.chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        );

        let formatted = "// µcad?>>\nCircle(r = 1mm);\n";
        for link in [
            link.clone(),
            data.to_string(),
            format!("https://play.mucad.org/{data}"),
            format!("#{data}"),
            format!("https://play.mucad.org/?code={data}"),
            format!("?example=1&code={data}"),
            // With padding to a multiple of four characters.
            format!("{data}{}", "=".repeat((4 - data.len() % 4) % 4)),
        ] {
            assert_eq!(decode(&link).as_deref(), Ok(formatted), "{link}");
        }

        // Code with errors is not formatted.
        let link = super::link("Circle( r= ;", false).expect("A link");
        assert_eq!(decode(&link).as_deref(), Ok("Circle( r= ;"));
    }

    /// Invalid links fail.
    #[test]
    fn decode_invalid() {
        assert!(matches!(
            decode("#a+b/c"),
            Err(ShareError::InvalidBase64(_))
        ));
        // No header.
        let code = URL_SAFE_NO_PAD.encode("Circle(r = 1mm);");
        assert!(matches!(decode(&code), Err(ShareError::InvalidData(_))));
        // Another kind of artifact.
        let mut bytes = serialize("x = 1;", false).expect("Serialized code");
        bytes[1] = (ArtifactKind::Ast as u8) << 4;
        assert!(matches!(
            deserialize(&bytes),
            Err(ShareError::InvalidData(_))
        ));
        // An incompatible version.
        bytes[1] = (ArtifactKind::Tokens as u8) << 4;
        bytes[2] = 99;
        assert!(matches!(
            deserialize(&bytes),
            Err(ShareError::InvalidData(_))
        ));
        // Truncated data.
        let bytes = serialize("x = 1;", false).expect("Serialized code");
        assert!(deserialize(&bytes[..bytes.len() - 1]).is_err());

        let too_long = URL_SAFE_NO_PAD.encode(vec![0; MAX_SERIALIZED_BYTES + 3]);
        assert!(matches!(decode(&too_long), Err(ShareError::TooLong(_))));
    }
}
